let current: Language = readLanguage();

function readLanguage(): Language {
  try {
    return window.localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "ko";
  } catch {
    return "ko";
  }
}

export function getLanguage(): Language {
  return current;
}

export function setLanguage(language: Language): void {
  current = language;
  document.documentElement.lang = language === "en" ? "en" : "ko";
  try {
    window.localStorage.setItem(STORAGE_KEY, language);
  } catch {}
}

export function t(key: string, values?: Record<string, string | number>): string {
  // Own keys only: a message like "constructor" must not find Object.prototype.
  const text = current === "en" && Object.hasOwn(EN, key) ? EN[key] : key;
  if (values === undefined) {
    return text;
  }
  // One pass with a function: values (names from a database error, say) may
  // contain "$&" or "{other}" and must come through as written.
  const filled = text.replace(/\{(\w+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : whole,
  );
  // English counts: "1 rows" reads "1 row".
  return current === "en" && String(values.count) === "1" ? singular(filled) : filled;
}

const PLURALS: Record<string, string> = {
  rows: "row",
  tables: "table",
  items: "item",
  runs: "run",
  statements: "statement",
  columns: "column",
  connections: "connection",
};

function singular(text: string): string {
  return text.replace(/(^|[^\d.,])1 (rows|tables|items|runs|statements|columns|connections)\b/g, (_, before: string, noun: string) =>
    `${before}1 ${PLURALS[noun]}`,
  );
}

// The server reports errors in Korean: a known message, or a known prefix
// ("SQLite 오류: …") before the database's own text. Shows them in the UI
// language; anything unrecognised comes through as sent.
const SERVER_PREFIXES: [RegExp, string][] = [
  [/^(SQLite|PostgreSQL|MySQL|SQL Server|Arrow) 오류: /, "$1 error: "],
  [/^파일을 찾을 수 없습니다: /, "File not found: "],
  [/^SQLite 데이터베이스 파일이 아닙니다: /, "Not a SQLite database file: "],
  [/^편집할 수 없습니다: /, "Can't edit: "],
  [/^내부 오류: /, "Internal error: "],
  [/^커밋하지 못해 트랜잭션을 롤백했습니다: /, "Couldn't commit, so the transaction was rolled back: "],
  [/^연결이 끊겨 커밋되었는지 알 수 없습니다: /, "The connection dropped; whether the commit went through is unknown: "],
  [/^배치가 실패해 트랜잭션이 커밋되었는지 알 수 없습니다: /, "The batch failed; whether the transaction was committed is unknown: "],
];

export function tServer(message: string): string {
  if (current !== "en") {
    return message;
  }
  if (Object.hasOwn(EN, message)) {
    return EN[message];
  }
  for (const [pattern, english] of SERVER_PREFIXES) {
    if (pattern.test(message)) {
      return message.replace(pattern, english);
    }
  }
  return message;
}

export function tTableCount(count: number): string {
  if (current === "en") {
    return `${count} ${count === 1 ? "table" : "tables"}`;
  }
  return `테이블 ${count}개`;
}

export function languageLabel(language: Language): string {
  return language === "en" ? "English" : "한국어";
}
