const SINGULAR = new RegExp(
  `(^|[^\\d.,])1 ((?:unsaved|new|more|distinct|column|search|older) )?(${Object.keys(PLURALS).join("|")})\\b`,
  "g",
);

function singular(text: string): string {
  return text.replace(
    SINGULAR,
    (_, before: string, between: string | undefined, noun: string) => `${before}1 ${between ?? ""}${PLURALS[noun]}`,
  );
}

