let current: Language = readLanguage();

function readLanguage(): Language {
  try {
    return window.localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "ko";
  } catch {
    return "ko";
  }
}

export function getLanguage(): Language {
  return current;
}

export function setLanguage(language: Language): void {
  current = language;
  document.documentElement.lang = language === "en" ? "en" : "ko";
  try {
    window.localStorage.setItem(STORAGE_KEY, language);
  } catch {}
}

export function t(key: string, values?: Record<string, string | number>): string {
  let text = current === "en" ? (EN[key] ?? key) : key;
  if (values !== undefined) {
    for (const [name, value] of Object.entries(values)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function tTableCount(count: number): string {
  if (current === "en") {
    return `${count} ${count === 1 ? "table" : "tables"}`;
  }
  return `테이블 ${count}개`;
}

export function languageLabel(language: Language): string {
  return language === "en" ? "English" : "한국어";
}
