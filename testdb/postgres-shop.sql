CREATE VIEW order_totals AS
SELECT o.id AS order_id, o.customer_id, c.full_name, o.status, o.ordered_at,
       count(oi.line_no) AS items, coalesce(sum(oi.quantity * oi.unit_price), 0) AS total
FROM orders AS o
JOIN customers AS c ON c.id = o.customer_id
LEFT JOIN order_items AS oi ON oi.order_id = o.id
GROUP BY o.id, o.customer_id, c.full_name, o.status, o.ordered_at;

CREATE VIEW product_ratings AS
SELECT p.id AS product_id, p.name, cat.name AS category, count(r.id) AS reviews,
       round(avg(r.rating), 2) AS average_rating
FROM products AS p
JOIN categories AS cat ON cat.id = p.category_id
LEFT JOIN reviews AS r ON r.product_id = p.id
GROUP BY p.id, p.name, cat.name;

-- Routine bodies name their tables in full: they run under the caller's
-- search_path, not the one this script sets.
CREATE FUNCTION customer_lifetime_value(customer INT) RETURNS NUMERIC
LANGUAGE sql STABLE AS $$
    SELECT coalesce(sum(oi.quantity * oi.unit_price), 0)
    FROM shop.orders AS o JOIN shop.order_items AS oi ON oi.order_id = o.id
    WHERE o.customer_id = customer AND o.status NOT IN ('cancelled', 'refunded')
$$;

CREATE PROCEDURE mark_shipped(target BIGINT)
LANGUAGE sql AS $$
    UPDATE shop.orders SET status = 'shipped', shipped_at = now() WHERE id = target AND status = 'paid'
$$;

CREATE FUNCTION log_order_status() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO shop.audit_log (table_name, row_id, action, detail)
    VALUES ('orders', NEW.id, 'status',
            jsonb_build_object('from', OLD.status, 'to', NEW.status));
    RETURN NEW;
END
$$;

CREATE TRIGGER orders_status_audit
AFTER UPDATE OF status ON orders
FOR EACH ROW WHEN (OLD.status IS DISTINCT FROM NEW.status)
EXECUTE FUNCTION log_order_status();

