-- A sample shop in its own schema, for trying TablePeek on something like a
-- real database: foreign keys (a self-reference, composite keys, CASCADE and
-- SET NULL), enums, JSONB, arrays, bytea, a table without a primary key,
-- awkward names, views, a function, a procedure and a trigger. The engine
-- tests don't read it. Runs once, when the container is first created.
CREATE SCHEMA shop;
SET search_path = shop, public;

CREATE TYPE customer_tier AS ENUM ('free', 'pro', 'enterprise');
CREATE TYPE order_status AS ENUM ('pending', 'paid', 'shipped', 'delivered', 'cancelled', 'refunded');

CREATE TABLE categories (
    id INT PRIMARY KEY,
    parent_id INT REFERENCES categories (id) ON DELETE SET NULL,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE
);
COMMENT ON TABLE categories IS 'Product categories; parent_id makes a tree';

CREATE TABLE customers (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    full_name TEXT NOT NULL,
    country CHAR(2),
    tier customer_tier NOT NULL DEFAULT 'free',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    preferences JSONB,
    signed_up_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    note TEXT
);

CREATE TABLE products (
    id INT PRIMARY KEY,
    category_id INT NOT NULL REFERENCES categories (id),
    sku VARCHAR(20) NOT NULL UNIQUE,
    name TEXT NOT NULL,
    price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    stock INT NOT NULL DEFAULT 0,
    tags TEXT[],
    attributes JSONB,
    thumbnail BYTEA,
    released_on DATE,
    discontinued BOOLEAN NOT NULL DEFAULT FALSE
);

-- A text primary key, which other tables point at.
CREATE TABLE coupons (
    code VARCHAR(16) PRIMARY KEY,
    discount_pct INT NOT NULL CHECK (discount_pct BETWEEN 1 AND 100),
    expires_on DATE,
    max_uses INT
);

CREATE TABLE orders (
    id BIGINT PRIMARY KEY,
    customer_id INT NOT NULL REFERENCES customers (id),
    status order_status NOT NULL DEFAULT 'pending',
    ordered_at TIMESTAMPTZ NOT NULL,
    shipped_at TIMESTAMPTZ,
    shipping_address JSONB,
    coupon_code VARCHAR(16) REFERENCES coupons (code) ON UPDATE CASCADE
);

CREATE TABLE order_items (
    order_id BIGINT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    line_no SMALLINT NOT NULL,
    product_id INT NOT NULL REFERENCES products (id),
    quantity INT NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10, 2) NOT NULL,
    PRIMARY KEY (order_id, line_no)
);

CREATE TABLE reviews (
    id INT PRIMARY KEY,
    product_id INT NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    customer_id INT REFERENCES customers (id) ON DELETE SET NULL,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    title TEXT,
    body TEXT,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE audit_log (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    table_name TEXT NOT NULL,
    row_id BIGINT NOT NULL,
    action TEXT NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    detail JSONB
);

-- No primary key: TablePeek reads it but won't edit rows it can't single out.
CREATE TABLE page_views (
    viewed_at TIMESTAMPTZ NOT NULL,
    path TEXT NOT NULL,
    customer_id INT,
    referrer TEXT,
    duration_ms INT
);

-- Names and values that need quoting or escaping.
CREATE TABLE "Edge Cases" (
    id INT PRIMARY KEY,
    "Mixed Case" TEXT,
    "한글 컬럼" TEXT,
    "with space" TEXT,
    "quote""inside" TEXT,
    big_number NUMERIC(38, 10),
    tiny_real REAL,
    happened_on DATE,
    happened_at TIMESTAMPTZ,
    payload JSONB,
    raw BYTEA
);

CREATE INDEX orders_customer_recent ON orders (customer_id, ordered_at DESC);
CREATE INDEX orders_open ON orders (status) WHERE status IN ('pending', 'paid');
CREATE INDEX products_category ON products (category_id);
CREATE INDEX products_tags ON products USING GIN (tags);
CREATE INDEX reviews_product_rating ON reviews (product_id, rating);
CREATE INDEX customers_email_lower ON customers (lower(email));

