CREATE TABLE categories (
    id NUMBER(10) PRIMARY KEY,
    parent_id NUMBER(10) REFERENCES categories (id) ON DELETE SET NULL,
    name VARCHAR2(100 CHAR) NOT NULL,
    slug VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE customers (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    email VARCHAR2(254 CHAR) NOT NULL UNIQUE,
    full_name VARCHAR2(200 CHAR) NOT NULL,
    country CHAR(2),
    tier VARCHAR2(10) DEFAULT 'free' NOT NULL CHECK (tier IN ('free', 'pro', 'enterprise')),
    is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0, 1)),
    preferences CLOB CHECK (preferences IS JSON),
    signed_up_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    note CLOB
);
COMMENT ON TABLE customers IS 'Who buys; preferences is a JSON object';

CREATE TABLE products (
    id NUMBER(10) PRIMARY KEY,
    category_id NUMBER(10) NOT NULL REFERENCES categories (id),
    sku VARCHAR2(20) NOT NULL UNIQUE,
    name VARCHAR2(200 CHAR) NOT NULL,
    price NUMBER(10, 2) NOT NULL CHECK (price >= 0),
    stock NUMBER(10) DEFAULT 0 NOT NULL,
    tags VARCHAR2(400 CHAR) CHECK (tags IS JSON),
    attributes CLOB CHECK (attributes IS JSON),
    thumbnail BLOB,
    released_on DATE,
    discontinued NUMBER(1) DEFAULT 0 NOT NULL
);

-- A text primary key, which another table points at.
CREATE TABLE coupons (
    code VARCHAR2(16 CHAR) PRIMARY KEY,
    discount_pct NUMBER(3) NOT NULL CHECK (discount_pct BETWEEN 1 AND 100),
    expires_on DATE,
    max_uses NUMBER(10)
);

CREATE TABLE orders (
    id NUMBER(19) PRIMARY KEY,
    customer_id NUMBER(10) NOT NULL REFERENCES customers (id),
    status VARCHAR2(10) DEFAULT 'pending' NOT NULL
        CHECK (status IN ('pending', 'paid', 'shipped', 'delivered', 'cancelled', 'refunded')),
    ordered_at TIMESTAMP WITH TIME ZONE NOT NULL,
    shipped_at TIMESTAMP WITH TIME ZONE,
    shipping_address VARCHAR2(400 CHAR) CHECK (shipping_address IS JSON),
    coupon_code VARCHAR2(16 CHAR) REFERENCES coupons (code)
);

CREATE TABLE order_items (
    order_id NUMBER(19) NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    line_no NUMBER(5) NOT NULL,
    product_id NUMBER(10) NOT NULL REFERENCES products (id),
    quantity NUMBER(10) NOT NULL CHECK (quantity > 0),
    unit_price NUMBER(10, 2) NOT NULL,
    PRIMARY KEY (order_id, line_no)
);

CREATE TABLE reviews (
    id NUMBER(10) PRIMARY KEY,
    product_id NUMBER(10) NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    customer_id NUMBER(10) REFERENCES customers (id) ON DELETE SET NULL,
    rating NUMBER(1) NOT NULL CHECK (rating BETWEEN 1 AND 5),
    title VARCHAR2(200 CHAR),
    body CLOB,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE audit_log (
    id NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    table_name VARCHAR2(64) NOT NULL,
    row_id NUMBER(19) NOT NULL,
    action VARCHAR2(16) NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    detail VARCHAR2(4000) CHECK (detail IS JSON)
);

-- No primary key: rows can't be edited by key.
CREATE TABLE page_views (
    viewed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    path VARCHAR2(200 CHAR) NOT NULL,
    customer_id NUMBER(10),
    referrer VARCHAR2(200 CHAR),
    duration_ms NUMBER(10)
);

-- Names and values that need quoting or escaping, and types only Oracle has.
CREATE TABLE "Edge Cases" (
    id NUMBER(10) PRIMARY KEY,
