-- A sample shop in its own schema (account SHOP in FREEPDB1), for trying
-- TablePeek on something like a real database: foreign keys (a
-- self-reference, composite and text keys, ON DELETE CASCADE and SET NULL),
-- CHECK lists in place of enums, JSON text, bytes, identity columns, a table
-- without a primary key, awkward names, views, a function, a procedure, a
-- package and a trigger. The engine tests only read its CUSTOMERS through
-- a synonym and log in as SHOP, an account without dictionary rights.
--
-- `make test-db` runs it as SYS on every start: once a run has finished
-- (the schema's CATEGORIES has its comment, set last), it skips the rest.
SET DEFINE OFF
SET FEEDBACK OFF
WHENEVER SQLERROR EXIT SUCCESS
DECLARE
    done NUMBER;
BEGIN
    SELECT COUNT(*) INTO done FROM dba_tab_comments
     WHERE owner = 'SHOP' AND table_name = 'CATEGORIES' AND comments IS NOT NULL;
    IF done > 0 THEN
        RAISE_APPLICATION_ERROR(-20000, 'seeded already');
    END IF;
END;
/
WHENEVER SQLERROR EXIT FAILURE
DECLARE
    started NUMBER;
BEGIN
    SELECT COUNT(*) INTO started FROM dba_users WHERE username = 'SHOP';
    IF started > 0 THEN
        RAISE_APPLICATION_ERROR(-20001,
            'Schema SHOP is half built: run make test-db-down ENGINE=oracle, then make test-db again.');
    END IF;
END;
/

