    "한글 컬럼" VARCHAR2(100 CHAR),
    "with space" VARCHAR2(100 CHAR),
    -- Oracle refuses a " inside a quoted name; $ and # are allowed.
    "price$per#unit" VARCHAR2(100 CHAR),
    big_number NUMBER(38, 10),
    tiny_real BINARY_FLOAT,
    happened_on DATE,
    happened_at TIMESTAMP(9) WITH TIME ZONE,
    local_at TIMESTAMP WITH LOCAL TIME ZONE,
    wait_for INTERVAL DAY(3) TO SECOND(3),
    term INTERVAL YEAR(3) TO MONTH,
    payload CLOB CHECK (payload IS JSON),
    raw_bytes RAW(100),
    national NVARCHAR2(50),
    fixed CHAR(5 CHAR)
);

