CREATE OR REPLACE PROCEDURE mark_shipped (p_target NUMBER) AS
BEGIN
    UPDATE orders SET status = 'shipped', shipped_at = SYSTIMESTAMP WHERE id = p_target AND status = 'paid';
END;
/

CREATE OR REPLACE PACKAGE shop_report AS
    FUNCTION orders_on (p_day DATE) RETURN NUMBER;
    PROCEDURE print_top_products (p_limit NUMBER DEFAULT 5);
END shop_report;
/
CREATE OR REPLACE PACKAGE BODY shop_report AS
    FUNCTION orders_on (p_day DATE) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM orders WHERE TRUNC(CAST(ordered_at AS DATE)) = TRUNC(p_day);
        RETURN v_count;
    END;

    PROCEDURE print_top_products (p_limit NUMBER DEFAULT 5) IS
    BEGIN
        FOR r IN (SELECT name, reviews FROM product_ratings ORDER BY reviews DESC FETCH FIRST p_limit ROWS ONLY) LOOP
            DBMS_OUTPUT.PUT_LINE(r.name || ': ' || r.reviews);
        END LOOP;
    END;
END shop_report;
/

CREATE OR REPLACE TRIGGER orders_status_audit AFTER UPDATE OF status ON orders FOR EACH ROW
WHEN (OLD.status <> NEW.status)
BEGIN
    INSERT INTO audit_log (table_name, row_id, action, detail)
    VALUES ('orders', :NEW.id, 'status', JSON_OBJECT('from' VALUE :OLD.status, 'to' VALUE :NEW.status));
END;
